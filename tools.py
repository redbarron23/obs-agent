"""
Data-access tools and Claude API tool definitions.

Each function returns a formatted string (not a DataFrame) so the
model gets clean, compact results.  The functions are pure — they
operate on in-memory DataFrames generated by data.py (deterministic
synthetic data).
"""

import pandas as pd

from data import (
    AZURE_DETAILS_DF,
    AZURE_SUMMARY_DF,
    GCP_DETAILS_DF,
    GCP_SUMMARY_DF,
)


def get_azure_top_overages(n: int = 5) -> str:
    """Top N Azure subscriptions by estimated 30-day overage cost."""
    df = AZURE_SUMMARY_DF.copy()
    top = df[df["estimated_overage_cost_30d"] > 0].nlargest(n, "estimated_overage_cost_30d")[
        ["subscription_id", "ingested_gb_30d", "overage_gb_30d", "estimated_overage_cost_30d"]
    ]
    if top.empty:
        return "No Azure subscriptions with overage found."
    return top.to_string(index=False)


def get_gcp_top_projects(n: int = 5) -> str:
    """Top N GCP projects by total logging cost."""
    df = GCP_SUMMARY_DF.copy()
    top = df[df["total_cost"] > 0].nlargest(n, "total_cost")[
        ["project_id", "total_cost", "currency"]
    ]
    if top.empty:
        return "No GCP projects with costs found."
    return top.to_string(index=False)


def get_daily_trend(platform: str, identifier: str) -> str:
    """Day-by-day cost/ingestion for a specific subscription or project."""
    platform = platform.lower()

    if platform == "azure":
        df = AZURE_DETAILS_DF.copy()
        sub = df[df["subscription_id"] == identifier]
        if sub.empty:
            return f"No Azure data found for subscription: {identifier}"
        daily = (
            sub.groupby("day")[["ingested_gb", "overage_gb", "estimated_overage_cost"]]
            .sum()
            .reset_index()
            .sort_values("day")
        )
        header = f"Daily cost trend for Azure subscription {identifier}:\n"
        return header + daily.to_string(index=False)

    elif platform == "gcp":
        df = GCP_DETAILS_DF.copy()
        proj = df[df["project_id"] == identifier]
        if proj.empty:
            return f"No GCP data found for project: {identifier}"
        daily = proj.groupby("day")[["cost"]].sum().reset_index().sort_values("day")
        header = f"Daily cost trend for GCP project {identifier}:\n"
        return header + daily.to_string(index=False)

    else:
        return f"Unknown platform '{platform}'. Use 'azure' or 'gcp'."


def _daily_spikes(
    df: pd.DataFrame,
    id_col: str,
    cost_col: str,
    threshold_pct: float,
) -> pd.DataFrame:
    """Days where an entity's cost jumped >= threshold_pct% vs the previous day."""
    daily = df.groupby([id_col, "day"])[cost_col].sum().reset_index().sort_values([id_col, "day"])
    daily["prev"] = daily.groupby(id_col)[cost_col].shift(1)
    daily["pct_change"] = (
        (daily[cost_col] - daily["prev"]) / daily["prev"].replace(0, float("nan")) * 100
    )
    return daily[(daily["pct_change"] >= threshold_pct) & (daily[cost_col] > 1)]


def _spike_lines(
    spikes: pd.DataFrame,
    id_col: str,
    cost_col: str,
    label: str,
    limit: int,
) -> list[str]:
    """Format the costliest *limit* spikes, noting when the list is truncated."""
    if spikes.empty:
        return []
    top = spikes.sort_values(cost_col, ascending=False).head(limit)
    lines = (
        label
        + " "
        + top[id_col].astype(str)
        + " on "
        + top["day"].astype(str)
        + ": +"
        + top["pct_change"].round(0).astype(int).astype(str)
        + "% ($"
        + top[cost_col].map("{:.2f}".format)
        + ")"
    ).tolist()
    if len(spikes) > limit:
        lines.insert(
            0,
            f"{label} showing the {limit} costliest of {len(spikes)} spikes:",
        )
    return lines


def find_spikes(
    threshold_pct: float = 50.0,
    platform: str = "all",
    limit: int = 10,
) -> str:
    """Detect days where cost jumped > threshold_pct% vs the previous day.

    Results are ranked by dollar cost (costliest first) and capped at *limit*
    per platform so the output stays readable. *platform* is 'azure', 'gcp'
    or 'all'.
    """
    platform = platform.lower()
    if platform not in ("all", "azure", "gcp"):
        return f"Unknown platform '{platform}'. Use 'azure', 'gcp' or 'all'."
    limit = max(1, int(limit))

    results: list[str] = []
    if platform in ("all", "azure"):
        spikes = _daily_spikes(
            AZURE_DETAILS_DF.copy(),
            "subscription_id",
            "estimated_overage_cost",
            threshold_pct,
        )
        results += _spike_lines(
            spikes,
            "subscription_id",
            "estimated_overage_cost",
            "[Azure]",
            limit,
        )
    if platform in ("all", "gcp"):
        spikes = _daily_spikes(GCP_DETAILS_DF.copy(), "project_id", "cost", threshold_pct)
        results += _spike_lines(spikes, "project_id", "cost", "[GCP]  ", limit)

    if not results:
        scope = (
            ""
            if platform == "all"
            else f" on {platform.upper() if platform == 'gcp' else platform.title()}"
        )
        return f"No spikes above {threshold_pct}% found{scope}."
    return "\n".join(results)


def compare_cross_cloud() -> str:
    """Compares total costs across Azure and GCP side by side.

    Returns a summary of total Azure overage cost, total GCP logging
    cost, and the cost split between the two clouds.  Useful for
    executive-level "what are we spending across both clouds?" questions.
    """
    az_total = AZURE_SUMMARY_DF["estimated_overage_cost_30d"].sum()
    gcp_total = GCP_SUMMARY_DF["total_cost"].sum()
    grand_total = az_total + gcp_total

    lines = [
        "Cross-Cloud Cost Summary (30 days)",
        "=" * 40,
        f"Azure total overage cost:  ${az_total:,.2f}",
        f"GCP total logging cost:    ${gcp_total:,.2f}",
        f"{'─' * 40}",
        f"Grand total:               ${grand_total:,.2f}",
        "",
        "Azure subscription breakdown:",
    ]
    for _, row in AZURE_SUMMARY_DF.sort_values(
        "estimated_overage_cost_30d", ascending=False
    ).iterrows():
        lines.append(f"  {row['subscription_id']}: ${row['estimated_overage_cost_30d']:,.2f}")

    lines.append("")
    lines.append("GCP project breakdown:")
    for _, row in GCP_SUMMARY_DF.sort_values("total_cost", ascending=False).iterrows():
        lines.append(f"  {row['project_id']}: ${row['total_cost']:,.2f}")

    return "\n".join(lines)


def get_label_coverage(limit: int = 10) -> str:
    """How many resources lack a usable team/env tag, plus example IDs.

    Raw tags are cleaned first ("Prod" → "prod", "o11y" → "observability"),
    so only genuinely missing or unrecognisable values count as unlabelled.
    """
    from labeling import LABELS, get_inference, get_suspects

    inf = get_inference()
    df = inf.df
    lines = [f"Label coverage across {len(df)} Azure subscriptions / GCP projects:"]
    for label in LABELS:
        missing = inf.unlabelled(label)
        lines.append(
            f"  {label}: {len(missing)} unlabelled ({len(missing) / len(df):.0%}), "
            f"{len(get_suspects(label))} labelled but suspected wrong"
        )
    either = df[df["team_clean"].isna() | df["env_clean"].isna()]
    limit = max(1, int(limit))
    lines.append(
        f"\nExamples missing team or env (showing {min(limit, len(either))} of {len(either)}):"
    )
    for _, row in either.head(limit).iterrows():
        lines.append(
            f"  {row['resource_id']} [{row['cloud']}] team={row['team_clean'] or '-'} "
            f"env={row['env_clean'] or '-'}"
        )
    return "\n".join(lines)


def suggest_labels(resource_id: str) -> str:
    """Predicted team / env / cost_center for one resource, with confidence and reasons."""
    from label_review import resource_report
    from labeling import LABELS

    r = resource_report(resource_id)
    if r is None:
        return f"No Azure subscription or GCP project found with id: {resource_id}"

    lines = [
        f"Label suggestions for {resource_id} [{r['cloud']}, parent {r['parent']}, "
        f"owners {', '.join(r['owners'])}]:"
    ]
    for label in LABELS:
        lr = r["labels"][label]
        if lr["status"] == "ok":
            lines.append(f"  tagged {label}={lr['current']} (consistent with similar resources)")
            continue
        if lr["status"] == "suspect":
            lines.append(
                f"  tagged {label}={lr['current']} but SUSPECTED WRONG: a model that never "
                f"saw this resource says {label}={lr['suggested']} "
                f"({lr['confidence']:.0%} confidence, needs review)"
            )
            continue
        raw = "none" if lr["raw"] is None else f"'{lr['raw']}' (unrecognised)"
        lines.append(f"  {label} untagged (raw value: {raw})")
        lines.append(
            f"    → suggest {label}={lr['suggested']} ({lr['confidence']:.0%} confidence, "
            f"{lr['action']}; via {lr['source']}: {lr['reason']})"
        )
        if lr["alternatives"]:
            alts = ", ".join(f"{a['value']} {a['confidence']:.0%}" for a in lr["alternatives"])
            lines.append(f"    alternatives: {alts}")
        if label == "team" and r["cost_center"]["implied"]:
            lines.append(f"    → implies cost_center={r['cost_center']['implied']}")
    return "\n".join(lines)


